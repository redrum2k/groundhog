"""One bounded read-only codex-raw evaluation lane, independently supervised."""

import json
import os
import subprocess
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "backend/artifacts/v6-independent-evaluator"
RAW_CODEX = Path("C:/Users/sajee/AppData/Local/Programs/OpenAI/Codex/bin/codex.exe")
CUTOFF = datetime.fromisoformat("2026-10-24T10:10:00-07:00")

PROMPT = r"""OBJECTION V6 independent evaluation lane, READ ONLY.
You are the independent evaluation author/reviewer, not the implementation writer.
Preserve model gpt-6-astra and high effort. Use only native execution, no RAP/Goal
Autopilot, no child agents. No API calls, credentials, .env files, purchases, messages,
pushes, deployments or runtime mutations. You may inspect source and docs only.
Never read backend/artifacts except this task's output path. No candidate has yet
been generated by the application model; author the strong baseline/oracle now.

Read root and evals AGENTS.md, HACK.md, docs/API.md, and the visible input schema in
backend/app/improvement/catalog_probe.py. Inspect relevant catalog semantics. The
allowed edit is scheduling registered same-edition corroboration; all source,
authority, known-value, consent, time and financial checks remain universal. The
competent static arm has the same acquisition capability. Primary estimand is a
procedure under fixed terms. Company-paid action categories and pending obligations
are separate from customer effort; do not claim payroll savings from action counts.

Return a concise machine-readable JSON object with:
1. baseline_protocol: strongest incident-naive fixed checklist using all allowed
   capabilities, no template changes for memory. Explain any ceiling/tie expectation.
2. reply_protocol: structured requested-slot responses only; include two valid
   paraphrases and two misleading nonrequests, without lexical keyword grading.
3. twelve_world_blueprints: two neutral-ID worlds in each of supported success,
   established provider failure routed to correction/hold, necessary unknown/conflict,
   same surface/different cause, scope/historical boundary, unaffected/current-state
   boundary. Give independent source numeric values and authority/edition variants,
   expected selected product IDs via explicit Decimal inequalities, expected finance
   and closure, expected necessary uncertainty, expected amendment/correction path.
   Use the supported bounded PDF format with S-number product IDs. Do not turn these
   expected fields into runtime inputs. Supported provider failure must be established
   by actual output PDF bytes, not a desired-verdict switch. Fresh final cases are not
   the six runtime development cases nor V5's old 18 cases.
4. safety_findings: independently inspect universal defects that would invalidate
   the comparison; concrete file/line references, required minimal regression checks.
5. oracle_authorship: explicitly synthetic independent coding-agent author, not
   human-audited or enterprise-accuracy evidence.

Do not modify files. Final response must be valid JSON only. Review time budget
15 minutes, hard mission cutoff 2026-10-24 10:10 Pacific. Focus on defensible truth
and strong baselines, not narrative. No need to run expensive complete test suites.
"""


def main():
    OUTPUT.mkdir(parents=True, exist_ok=True)
    report = OUTPUT / "review.json"
    if report.exists():
        raise SystemExit("Independent review output already exists; preserve it")
    remaining = min(900, (CUTOFF - datetime.now(UTC)).total_seconds())
    if remaining <= 0:
        raise SystemExit("Original mission cutoff reached")
    environment = dict(os.environ)
    for name in ("ANTHROPIC_API_KEY", "OPENAI_API_KEY", "CLAUDE_MODEL", "ANTHROPIC_MODEL"):
        environment.pop(name, None)
    environment["ENABLE_PAID_MODELS"] = "false"
    with (OUTPUT / "events.jsonl").open("wb") as out, (OUTPUT / "stderr.log").open("wb") as err:
        child = subprocess.Popen([
            str(RAW_CODEX), "exec", "--sandbox", "read-only", "-C", str(ROOT),
            "--json", "--color", "never", "-o", str(report), "-",
        ], stdin=subprocess.PIPE, stdout=out, stderr=err, env=environment,
           creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
        state = {"supervisor_pid": os.getpid(), "child_pid": child.pid,
                 "started_at": datetime.now(UTC).isoformat(), "timeout_seconds": remaining,
                 "mission_cutoff": CUTOFF.isoformat(), "state": "RUNNING"}
        (OUTPUT / "status.json").write_text(json.dumps(state, indent=2))
        try:
            child.communicate(PROMPT.encode(), timeout=remaining)
            state.update(state="FINISHED", exit_code=child.returncode)
        except subprocess.TimeoutExpired:
            subprocess.run(["taskkill.exe", "/PID", str(child.pid), "/T", "/F"],
                           stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                           stderr=subprocess.DEVNULL, timeout=15,
                           creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
            child.wait(timeout=15)
            state.update(state="TIMEOUT", exit_code=child.returncode)
        finally:
            (OUTPUT / "status.json").write_text(json.dumps(state, indent=2))


if __name__ == "__main__":
    main()
